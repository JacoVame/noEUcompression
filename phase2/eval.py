#!/usr/bin/env python3
"""Phase-1 eval harness CLI — FROZEN after Phase 1.

    python eval.py --embedding random [--dataset ...] [--dim ...] [--seed ...]

Loads a hierarchy, obtains a matrix of pairwise embedding distances, scores it
(MAP, mean rank, average distortion), prints the crowding histogram and the
distortion-vs-depth curve, and writes the JSON + the two figures to `out/`
with the seed in every filename.

Built before any embedding exists, on purpose: the ruler must not be shaped by
the thing it measures. `--embedding random` is the null control — whatever it
scores is the floor that Phases 2-3 have to beat.

Contract for builder sessions (Phases 2-3)
------------------------------------------
Do not edit this file or `harness/`. Add a module `embeddings/<name>.py`
exposing:

    def build(hierarchy, dim, seed):
        '''Return (coords, emb_dist).

        coords   : (n, k) array for inspection/plots, or None
        emb_dist : (n, n) symmetric non-negative array of pairwise distances
                   in whatever geometry the module implements
        '''

then run `python eval.py --embedding <name> ...`. The harness imports it by
name; nothing here needs to change.
"""
import argparse
import importlib
import json
import os
import sys

# PYTHONSAFEPATH=1 is mandatory in this project (see CLAUDE.md), and it stops
# Python from putting the script's own directory on sys.path. Put it back
# explicitly, resolved from __file__ rather than the CWD, so that `harness` and
# `embeddings` import no matter where eval.py is invoked from.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import numpy as np  # noqa: E402

from harness import datasets, metrics, plots  # noqa: E402

DEFAULT_SEED = 20260716
ASCII_BINS = 20
ASCII_WIDTH = 44


def main(argv=None):
    args = _parse_args(argv)
    _seed_everything(args.seed)

    hierarchy = datasets.load(args.dataset, seed=args.seed)
    coords, emb_dist = _build_embedding(args.embedding, hierarchy, args.dim, args.seed)
    result = metrics.evaluate(hierarchy, emb_dist)

    os.makedirs(args.out, exist_ok=True)
    stem = f"{args.embedding}_{args.dataset}_d{args.dim}_seed{args.seed}"
    hist_path = os.path.join(args.out, f"crowding_{stem}.png")
    curve_path = os.path.join(args.out, f"depth_{stem}.png")
    json_path = os.path.join(args.out, f"eval_{stem}.json")

    plots.crowding_histogram(
        hist_path, result["emb_dist_pairs"], result["graph_dist_pairs"],
        f"crowding — {args.embedding} / {args.dataset} / d={args.dim} / seed={args.seed}")
    plots.depth_curve(
        curve_path, result["depth_levels"], result["distortion_by_depth"],
        result["pairs_by_depth"],
        f"distortion vs depth — {args.embedding} / {args.dataset} / "
        f"d={args.dim} / seed={args.seed}")

    record = {
        "embedding": args.embedding,
        "dataset": args.dataset,
        "dim": args.dim,
        "seed": args.seed,
        **{k: v for k, v in result.items() if not isinstance(v, np.ndarray)},
        "figures": {"crowding": hist_path, "depth_curve": curve_path},
    }
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(record, fh, indent=2, sort_keys=True)
        fh.write("\n")

    _report(args, result, coords, hist_path, curve_path, json_path)
    return 0


def _parse_args(argv):
    p = argparse.ArgumentParser(
        description="Phase-1 eval harness: score an embedding against a hierarchy.")
    p.add_argument("--embedding", required=True,
                   help="'random' (built-in null control) or a module name under "
                        "embeddings/ exposing build(hierarchy, dim, seed)")
    p.add_argument("--dataset", default="synthetic-tree", choices=datasets.DATASETS)
    p.add_argument("--dim", type=int, default=2)
    p.add_argument("--seed", type=int, default=DEFAULT_SEED)
    p.add_argument("--out", default="out")
    return p.parse_args(argv)


def _seed_everything(seed):
    np.random.seed(seed)
    try:
        import torch
    except ImportError:  # harness itself needs no torch; embeddings do
        return
    torch.manual_seed(seed)


def _build_embedding(name, hierarchy, dim, seed):
    if name == "random":
        return _random_embedding(hierarchy, dim, seed)
    try:
        module = importlib.import_module(f"embeddings.{name}")
    except ImportError as exc:
        raise SystemExit(
            f"no embedding {name!r}: expected 'random' or embeddings/{name}.py "
            f"({exc})") from exc
    coords, emb_dist = module.build(hierarchy, dim, seed)
    return coords, np.asarray(emb_dist, dtype=np.float64)


def _random_embedding(hierarchy, dim, seed):
    """Isotropic Gaussian points with the Euclidean metric: the null control."""
    rng = np.random.default_rng(seed)
    coords = rng.standard_normal((hierarchy.n, dim))
    sq = np.einsum("ij,ij->i", coords, coords)
    d2 = sq[:, None] + sq[None, :] - 2.0 * (coords @ coords.T)
    np.maximum(d2, 0.0, out=d2)
    dist = np.sqrt(d2)
    dist = 0.5 * (dist + dist.T)
    np.fill_diagonal(dist, 0.0)
    return coords, dist


def _report(args, result, coords, hist_path, curve_path, json_path):
    print(f"dataset        : {args.dataset} "
          f"({result['n_nodes']} nodes, {result['n_pairs']} pairs)")
    print(f"embedding      : {args.embedding}  dim={args.dim}  seed={args.seed}"
          + ("" if coords is None else f"  coords={coords.shape}"))
    print()
    print(f"MAP            : {result['map']:.6f}")
    print(f"mean rank      : {result['mean_rank']:.4f}")
    print(f"avg distortion : {result['avg_distortion']:.6f}  "
          f"(at global scale {result['distortion_scale']:.6f})")
    print()
    _print_histogram(result["emb_dist_pairs"], result["graph_dist_pairs"])
    print()
    _print_depth_curve(result["depth_levels"], result["distortion_by_depth"],
                       result["pairs_by_depth"])
    print()
    print(f"wrote {json_path}")
    print(f"wrote {hist_path}")
    print(f"wrote {curve_path}")
    print()
    print("reproduce with:")
    print(f"  {_interpreter()} eval.py --embedding {args.embedding} "
          f"--dataset {args.dataset} --dim {args.dim} --seed {args.seed} "
          f"--out {args.out}")


def _print_histogram(emb_pairs, graph_pairs):
    counts, edges = np.histogram(emb_pairs, bins=ASCII_BINS)
    peak = max(int(counts.max()), 1)
    print("crowding histogram — scaled embedding distance "
          f"(graph: {graph_pairs.min():.0f}..{graph_pairs.max():.0f} hops, "
          f"mean {graph_pairs.mean():.2f})")
    for i, c in enumerate(counts):
        bar = "#" * int(round(ASCII_WIDTH * c / peak))
        print(f"  [{edges[i]:6.2f},{edges[i + 1]:6.2f})  {bar:<{ASCII_WIDTH}} {c}")
    print(f"  spread: emb sigma/mean = {emb_pairs.std() / emb_pairs.mean():.4f}  "
          f"vs graph {graph_pairs.std() / graph_pairs.mean():.4f}")


def _print_depth_curve(levels, values, counts):
    peak = max(max(values), 1e-12)
    print("depth curve — mean distortion by depth of the deeper endpoint")
    for level, value, count in zip(levels, values, counts):
        bar = "#" * int(round(ASCII_WIDTH * value / peak))
        print(f"  depth {level:>2}  {value:8.4f}  {bar:<{ASCII_WIDTH}} "
              f"n={count}")


def _interpreter():
    """The path recorded by setup.ps1, so the printed command is runnable."""
    try:
        with open(".venv-path", encoding="ascii") as fh:
            recorded = fh.read().strip()
        if recorded:
            return recorded
    except OSError:
        pass
    return sys.executable


if __name__ == "__main__":
    sys.exit(main())
